import { expect, test, uid, usePersona } from '../helpers/fixtures';
usePersona('admin');

test('attachment review and call review require approval and only save a confirmed internal note', async ({ page, api, ticket, context }) => {
  const file = await api.insert('File', { file_name: `qa-${uid()}.txt`, content: 'A private attachment for review.', is_private: 1, attached_to_doctype: 'HD Ticket', attached_to_name: ticket.name });
  const recording = await api.insert('Pramaan Call', { ticket: ticket.name, request_id: crypto.randomUUID(), state: 'Running', job_id: 'job-qa-unavailable', recording_enabled: 1, result_ref: 'ref_01ARZ3NDEKTSV4RRFFQ69G5FAV' });
  const comments = () => api.list('Comment', { filters: { reference_doctype: 'HD Ticket', reference_name: ticket.name, comment_type: 'Comment' } });
  const before = (await comments()).length;
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto(`/helpdesk/tickets/${ticket.name}`);
  await page.getByText('Pramaan assistance', { exact: true }).click();
  await page.getByRole('button', { name: 'Draft a reply', exact: true }).click();
  await expect(page.getByLabel('Suggested text', { exact: true })).toHaveValue(/Suggested support text/);
  await page.getByLabel('Attachment', { exact: true }).selectOption(file.name);
  await page.getByRole('button', { name: 'Read attachment text', exact: true }).click();
  await expect(page.getByLabel('Suggested text', { exact: true })).toHaveValue('A private attachment for review.');
  await page.getByRole('button', { name: 'Summarise attachment', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Approve and summarise', exact: true })).toBeVisible();
  expect((await comments()).length).toBe(before);
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Summarise attachment', exact: true }).click();
  await page.getByRole('button', { name: 'Approve and summarise', exact: true }).click();
  await expect(page.getByLabel('Attachment summary', { exact: true })).toHaveValue(/private attachment describes/);
  await page.getByRole('button', { name: 'Copy summary', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('Check the supplied details.');
  expect((await comments()).length).toBe(before);
  await page.goto('/helpdesk/call-logs');
  const row = page.locator('.border-b').filter({ has: page.getByRole('link', { name: `Ticket ${ticket.name}`, exact: true }) });
  await row.getByRole('button', { name: 'Check status', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Could not confirm this request. Check its status before trying again.');
  await api.update('Pramaan Call', recording.name, { state: 'Ended' });
  await page.reload();
  await row.getByRole('button', { name: 'Review call', exact: true }).click();
  await row.getByLabel('Call review checks').fill('Agent explained the next step');
  await row.getByRole('button', { name: 'Get estimate', exact: true }).click();
  await row.getByRole('button', { name: 'Approve and review call', exact: true }).click();
  await expect(row.getByText('Evidence found', { exact: true })).toBeVisible();
  expect((await comments()).length).toBe(before);
  await row.getByRole('button', { name: 'Confirm and save internal note', exact: true }).click();
  await expect(row.getByRole('button', { name: 'Internal note saved', exact: true })).toBeDisabled();
  expect((await comments()).length).toBe(before + 1);
});
